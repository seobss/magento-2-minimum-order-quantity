namespace Bss\Limitcartqty\Model\System\Config\Backend;

class ConfigModel extends \Magento\Framework\App\Config\Value
{
    protected $configValue = null;

    public function __construct(
        \Magento\Framework\Model\Context $context,
        \Magento\Framework\Registry $registry,
        \Magento\Framework\App\Config\ScopeConfigInterface $config,
        \Magento\Framework\App\Cache\TypeListInterface $cacheTypeList,
        \Bss\Limitcartqty\Helper\ConfigValue $configValue,
        \Magento\Framework\Model\ResourceModel\AbstractResource $resource = null,
        \Magento\Framework\Data\Collection\AbstractDb $resourceCollection = null,
        array $data = []
    ) {
        $this->configValue = $configValue;
        parent::__construct(
            $context,
            $registry,
            $config,
            $cacheTypeList,
            $resource,
            $resourceCollection,
            $data
        );
    }
    
    protected function _afterLoad()
    {
        $value = $this->getValue();
        $value = $this->configValue->makeArrayFieldValue($value);
        $this->setValue($value);
    }

    public function beforeSave()
    {
        $value = $this->getValue();
        $value = $this->configValue->makeStorableArrayFieldValue($value);
        $this->setValue($value);
    }
}
